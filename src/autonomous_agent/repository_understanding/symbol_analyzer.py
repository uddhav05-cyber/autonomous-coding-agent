@dataclass
class Symbol:
    """Represents a symbol (function, class, variable) in the codebase."""
    name: str
    symbol_type: str  # 'function', 'class', 'variable', 'import', etc.
    file_path: Path
    line_number: int
    column: int = 0
    end_line_number: Optional[int] = None
    end_column: int = 0
    scope: str = ""  # e.g., "module", "class.MyClass", "function.my_func"
    is_definition: bool = True
    is_exported: bool = False
    is_imported: bool = False
    aliases: List[str] = field(default_factory=list)
    # For imports/exports
    imported_from: Optional[Path] = None
    imported_name: Optional[str] = None
    exported_as: Optional[str] = None


@dataclass
class DependencyEdge:
    """Represents a dependency relationship between files."""
    source_file: Path
    target_file: Path
    dependency_type: str  # 'import', 'require', 'include', etc.
    symbol_name: Optional[str] = None
    line_number: int = 0
    # For configuration-based dependencies
    dependency_spec: Optional[str] = None  # e.g., "lodash^4.17.21"
    is_resolved: bool = True
    weight: float = 1.0  # Strength of dependency (for weighting)


@dataclass
class SpecialFileClassification:
    """Classification of a file as special type."""
    file_path: Path
    is_generated: bool = False
    is_large: bool = False
    is_binary: bool = False
    size_lines: int = 0
    size_bytes: int = 0
    confidence: float = 0.0  # Confidence in classification (0.0-1.0)
    reasons: List[str] = field(default_factory=list)


class SymbolDependencyAnalyzer:
    """
    Analyzes symbols and dependencies in the codebase.

    Provides:
    - Symbol extraction using AST parsing (with regex fallback)
    - Import/export/require statement analysis
    - Configuration-driven dependency extraction
    - Basic call graph construction
    - Special file type detection and classification
    """

