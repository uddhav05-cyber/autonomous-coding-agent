    def _parse_requirements_txt(self, file_path: Path) -> List[Dict[str, Any]]:
        """Parse requirements.txt for dependencies."""
        dependencies = []

        try:
            with open(file_path, 'r') as f:
                lines = f.readlines()

            for line_num, line in enumerate(lines, 1):
                line = line.strip()
                if line and not line.startswith('#'):
                    # Parse requirement line (simplified)
                    # Handle formats like: package==1.0.0, package>=1.0, package, etc.
                    parts = re.split(r'[<>=!~]', line, 1)
                    name = parts[0].strip()
                    if name:
                        version = line[len(name):].strip() if len(line) > len(name) else ''
                        dependencies.append({
                            'name': name,
                            'version': version,
                            'type': 'requirement',
                            'line_number': line_num
                        })
        except (OSError, IOError):
            pass

        return dependencies

